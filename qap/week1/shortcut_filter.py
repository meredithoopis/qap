"""Shortcut filter (IG-Sub construction, proposal Sec. 6.1).

A retained task is kept only if a diffusion policy trained on L0-L2 of that task FAILS the
substituted variant (L3 success < 50%), so substitution cannot be solved with the
original strategy. Uses the IG DP baseline unchanged; only per-task configs are new.

    # 1) write per-task dataset/eval configs + a background launcher
    python -m qap.week1.shortcut_filter prepare --gpus 0 1
    # 2) run it in the background (train + eval, one task after another per GPU)
    nohup bash qap_runs/shortcut/run_shortcut.sh > qap_runs/shortcut/run.log 2>&1 &
    # 3) when finished
    python -m qap.week1.shortcut_filter summarize
    python -m qap.week1.screen_tasks --apply-shortcut-results qap_runs/shortcut/summary.json
"""

from __future__ import annotations

import argparse
import json
import shlex
from pathlib import Path
from typing import Dict, List

from qap.common.io import load_json, save_json
from qap.common.paths import FROZEN_DIR, REPO_ROOT, sub
from qap.common.tasks import dataset_id, human_id

DP_TRAIN = "examples.baselines.diffusion_policy.train_dp_imitator"
DP_EVAL = "examples.baselines.diffusion_policy.parallel_eval_dp"
LM = "examples/baselines/lerobot_dataset"


def _entry(repo: str, rng: str) -> Dict:
    return {"repo_id": repo, "root": repo, "train": rng, "test": ""}


def write_task_configs(task: str, out: Path, n_train: int) -> Dict[str, Path]:
    out.mkdir(parents=True, exist_ok=True)
    h = human_id(task)
    if h is None:
        raise KeyError(f"no human id for {task}")
    files = {
        "sim_train": [_entry(dataset_id(task, l), f"0:{n_train}") for l in ("L0", "L1", "L2")],
        "human_train": [_entry(h, f"0:{n_train}")],
        "sim_eval": [_entry(dataset_id(task, l), f"0:{n_train}") for l in ("L0", "L1", "L2", "L3")],
        "human_eval": [_entry(h, f"0:{n_train}")],
    }
    paths = {}
    for k, v in files.items():
        p = out / f"{k}_{task}.json"
        save_json(v, p)
        paths[k] = p
    el = out / f"eval_list_{task}.txt"
    el.write_text(f"{dataset_id(task, 'L0')}\n{dataset_id(task, 'L3')}\n", encoding="utf-8")
    paths["eval_list"] = el
    return paths


def prepare(args) -> None:
    frozen = load_json(FROZEN_DIR / "frozen_tasks.json")
    tasks = [t["task"] for t in frozen["retained"]]
    # test and calibration tasks first: their verdicts matter most, so they finish earliest
    sp = FROZEN_DIR / "splits.json"
    if sp.exists():
        rank = {t: i for i, k in enumerate(("test", "calibration", "train"))
                for t in load_json(sp)["splits"].get(k, [])}
        tasks.sort(key=lambda t: rank.get(t, 9))
    root = sub("shortcut")
    lines: List[str] = ["#!/bin/bash", "# generated by qap.week1.shortcut_filter prepare", "set -uo pipefail",
                        f"cd {shlex.quote(str(REPO_ROOT))}", "export PYTHONPATH=$PWD:${PYTHONPATH:-}",
                        f"BACKBONE=${{BACKBONE:-{args.backbone}}}", f"EPOCHS=${{EPOCHS:-{args.epochs}}}", ""]
    per_gpu: Dict[str, List[str]] = {g: [] for g in args.gpus}
    for i, task in enumerate(tasks):
        gpu = args.gpus[i % len(args.gpus)]
        p = write_task_configs(task, root / "configs", args.n_train)
        exp_name = f"qap_shortcut_{task}"      # trainer writes runs/<exp_name>-<YYYYMMDD>/checkpoints
        eval_dir = root / "eval" / task
        train = (
            f"CUDA_VISIBLE_DEVICES={gpu} python -m {DP_TRAIN} "
            f"--human-root {args.human_root} --sim-root {args.sim_root} "
            f"--human-dataset-file {p['human_train']} --sim-dataset-file {p['sim_train']} "
            f"--task-mapping-file {LM}/task_mapping.json "
            f"--human-task-description-file {LM}/task_desc/human_desc.json "
            f"--sim-task-description-file {LM}/task_desc/sim_desc.json "
            f"--input-mode video_only --task-encoder-type frozen_backbone --frozen-backbone-type $BACKBONE "
            f"--frozen-backbone-num-frames 10 --frozen-backbone-adapter-layers 1 --frozen-backbone-seq-patches 32 "
            f"--control-mode pd_joint_pos --batch-size {args.batch_size} --total-epochs $EPOCHS --lr 1e-4 "
            f"--save-epoch-freq 50 --num-dataload-workers {args.workers} --env-id {('TwoRobot' + task + '-v1')} "
            f"--max-episode-steps 500 --unet-dims 352 704 1408 2816 --exp-name {exp_name}"
        )
        evalc = (
            f"CUDA_VISIBLE_DEVICES={gpu} python -m {DP_EVAL} --eval-config {p['eval_list']} "
            f"--checkpoint $(ls -td runs/{exp_name}-*/checkpoints/final_model.pt | head -1) "
            f"--output-dir {eval_dir} --input-mode video_only --task-encoder-type frozen_backbone "
            f"--frozen-backbone-type $BACKBONE --frozen-backbone-num-frames 10 --action-dim 16 --state-dim 18 "
            f"--obs-horizon 1 --pred-horizon 16 --obs-latent-dim 256 --task-latent-dim 256 --num-diffusion-iters 100 "
            f"--num-episodes {args.eval_episodes} --num-envs 1 --max-episode-steps 500 --control-mode pd_joint_pos "
            f"--obs-mode rgb --sim-backend physx_cpu --shader {args.shader} --use-ddim --num-ddim-steps 10 "
            f"--human-root {args.human_root} --sim-root {args.sim_root} --human-config {p['human_eval']} "
            f"--sim-config {p['sim_eval']} --task-mapping {LM}/task_mapping.json "
            f"--human-task-desc {LM}/task_desc/human_desc.json --sim-task-desc {LM}/task_desc/sim_desc.json "
            f"--num-gpus 1 --gpu-ids {gpu} --max-procs-per-gpu {args.eval_procs}"
        )
        per_gpu[gpu] += [f"echo '[shortcut] {task} train'", train, f"echo '[shortcut] {task} eval'", evalc]
        # Standalone, resumable per-task script (one Slurm array task each; GPU picked by Slurm).
        # Training is skipped if a final_model.pt exists; the IG evaluator skips finished envs.
        tdir = root / "tasks"
        tdir.mkdir(parents=True, exist_ok=True)
        ckpt_glob = f"runs/{exp_name}-*/checkpoints/final_model.pt"
        task_lines = lines[:7] + [
            f"echo \"[shortcut] {task} on $(hostname) GPU=${{CUDA_VISIBLE_DEVICES:-?}} $(date)\"",
            f"if ls {ckpt_glob} >/dev/null 2>&1; then",
            f"  echo '[shortcut] {task}: final_model.pt exists, skipping training'",
            "else",
            # resume from the newest epoch checkpoint (saved every 50 epochs) after a time-limit kill
            f"  RESUME=$(ls -t runs/{exp_name}-*/checkpoints/epoch_*.pt 2>/dev/null | head -1 || true)",
            f"  [[ -n \"$RESUME\" ]] && echo \"[shortcut] {task}: resuming from $RESUME\"",
            "  " + train.replace(f"CUDA_VISIBLE_DEVICES={gpu} ", "") + " ${RESUME:+--resume-from $RESUME} || exit 1",
            "fi",
            f"echo \"[shortcut] {task} eval $(date)\"",
            # The IG evaluator sets CUDA_VISIBLE_DEVICES=<gpu-id> for its workers and checks free
            # memory with nvidia-smi --id; pass the id Slurm assigned and skip the memory check
            # (inside a Slurm GPU cgroup nvidia-smi may number the GPU differently).
            evalc.replace(f"CUDA_VISIBLE_DEVICES={gpu} ", "").replace(
                f"--gpu-ids {gpu}", "--gpu-ids ${CUDA_VISIBLE_DEVICES%%,*} --min-free-mem-gb 0"),
            f"echo \"[shortcut] {task} done $(date)\"",
        ]
        (tdir / f"{task}.sh").write_text("\n".join(task_lines) + "\n", encoding="utf-8")
    for gpu, cmds in per_gpu.items():
        lines.append("(")
        lines += [f"  {c}" for c in cmds]
        lines.append(") &")
    lines += ["wait", "echo '[shortcut] all done'"]
    script = root / "run_shortcut.sh"
    script.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (root / "tasks.txt").write_text("\n".join(tasks) + "\n", encoding="utf-8")
    print(f"wrote configs under {root/'configs'}, launcher {script} and per-task scripts "
          f"{root/'tasks'}/<task>.sh for {len(tasks)} tasks (list: {root/'tasks.txt'})")


def summarize(args) -> None:
    root = sub("shortcut")
    frozen = load_json(FROZEN_DIR / "frozen_tasks.json")
    out: Dict[str, Dict] = {}
    for t in [r["task"] for r in frozen["retained"]]:
        recs = []
        for f in (root / "eval" / t).glob("*.json"):
            try:
                data = json.load(open(f, encoding="utf-8"))
            except Exception:
                continue
            if isinstance(data, list):
                recs += [r for r in data if r.get("status") == "success"]
        by_env = {}
        for r in sorted(recs, key=lambda r: r.get("timestamp", "")):
            by_env[r["env_id"]] = r
        l3 = by_env.get(dataset_id(t, "L3"), {})
        l0 = by_env.get(dataset_id(t, "L0"), {})
        sr3 = l3.get(f"{args.metric}_mean")
        sr0 = l0.get(f"{args.metric}_mean")
        out[t] = dict(l0_success=sr0, l3_success=sr3, evaluated=sr3 is not None,
                      passes=(sr3 is not None and sr3 < args.threshold))
    summary = dict(metric=args.metric, threshold=args.threshold, tasks=out)
    save_json(summary, root / "summary.json")
    for t, r in out.items():
        print(f"{t:24s} L0={r['l0_success']} L3={r['l3_success']} -> {'KEEP' if r['passes'] else 'DROP' if r['evaluated'] else 'MISSING'}")
    missing = [t for t, r in out.items() if not r["evaluated"]]
    if missing:
        print(f"WARNING: no L3 result for {missing}. Do not apply the summary until every task is evaluated "
              f"(screen_tasks --apply-shortcut-results refuses while results are missing).")


def main() -> None:
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("prepare")
    p.add_argument("--gpus", nargs="+", default=["0"])
    p.add_argument("--human-root", default="demos/imitator_human_v1", help="folder containing human_H<N>/ datasets")
    p.add_argument("--sim-root", default="demos/imitator_sim_v1_zed2i", help="folder containing L<k>_TwoRobot<Task>-v1/ datasets")
    p.add_argument("--backbone", default="dinov2_vitl14")
    p.add_argument("--epochs", type=int, default=100,
                   help="IG trains C45 for 10 epochs (~80k steps at batch 256); 100 epochs on one task's "
                        "L0-L2 (~150 episodes) is ~35k steps at batch 128, ~20x IG's per-task exposure")
    p.add_argument("--batch-size", type=int, default=128)
    p.add_argument("--workers", type=int, default=14, help="video-decoding workers (Slurm job has 16 CPUs)")
    p.add_argument("--n-train", type=int, default=50)
    p.add_argument("--eval-episodes", type=int, default=20)
    p.add_argument("--eval-procs", type=int, default=2, help="evaluation processes on the GPU (L0 and L3 in parallel)")
    p.add_argument("--shader", default="default",
                   help="SAPIEN shader for DP evaluation renders. IG's own runs use rt-fast, which needs the "
                        "OptiX denoiser (libnvoptix); 'default' is rasterised and works on any GPU driver")
    s = sp.add_parser("summarize")
    s.add_argument("--metric", default="success_once")
    s.add_argument("--threshold", type=float, default=0.5)
    args = ap.parse_args()
    prepare(args) if args.cmd == "prepare" else summarize(args)


if __name__ == "__main__":
    main()
